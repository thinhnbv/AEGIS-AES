#!/usr/bin/env python3

import argparse
import secrets
import sys
import time

from dataclasses import dataclass


REQUEST_PREAMBLE = 0xA5
RESPONSE_PREAMBLE = 0x5A
AES_COMMAND = 0x01

REQUEST_SIZE = 36
RESPONSE_SIZE = 37

FLAG_RAW_VALID = 1 << 0
FLAG_PROTECTED_VALID = 1 << 1
FLAG_ALARM = 1 << 2
FLAG_PROTECTED_BLOCKED = 1 << 3
FLAG_FRAME_ERROR = 1 << 7
KLG_STATUS_MASK = 1 << 0

FIPS_KEY = bytes.fromhex(
    "2b7e151628aed2a6abf7158809cf4f3c"
)
FIPS_PLAINTEXT = bytes.fromhex(
    "3243f6a8885a308d313198a2e0370734"
)
FIPS_CIPHERTEXT = bytes.fromhex(
    "3925841d02dc09fbdc118597196a0b32"
)
T01_TRIGGER = bytes.fromhex(
    "deadbeefcafebabe0000000000000000"
)
T02_TRIGGER = bytes.fromhex(
    "00112233445566778899aabbccddeeff"
)
T03_TRIGGER = bytes.fromhex(
    "123456789abcdef00000000000000001"
)
T04_TRIGGER_A = bytes(16 * 0xA5)
T04_TRIGGER_B = bytes(16 * 0x5A)
T04_TRIGGER_C = bytes(16 * 0xFF)
T05_TRIGGER = bytes(16 * 0xFF)
ZERO_BLOCK = bytes(16)

# How many encryptions the T02 slow-leak counter must accumulate
# before the Trojan fires (2^16), plus the KLG confirmation window
# (a few frames after the leak starts). One extra margin block.
T02_DEFAULT_REPEAT = 65552

# ------------------------------------------------------------------
# Per-case contract for the one-command `case T0x` demo.
#
# `expected_mask` - detector bits that MUST be set on the final
#   trigger frame (subset semantics: extras are allowed). Values
#   match verif/cfg/<CASE>.cfg generated by `make gen-cfg` on the
#   current branch (T01=01 KLG, T02=01 KLG, T03=14 RCM+ORC,
#   T04=0A FIC+RED, T05=04 RCM). These are the exact masks the
#   security testbench enforces, so the on-board demo check agrees
#   with `make security CASE=...`.
# `raw_valid` - whether the RAW (unprotected) path returns a result
#   on the trigger frame. T05's DoS hangs the raw core, so the FSM
#   watchdog suppresses RAW_VALID.
# `raw_valid_post` - same, for the post-LOCKDOWN clean frame. The
#   T05 Trojan only fires on the 0xFF trigger; the post frame is a
#   normal FIPS vector, so the raw path completes again.
# ------------------------------------------------------------------
CASE_CONTRACT = {
    "T01": {
        "label": "key dump",
        "expected_mask": 0x01,      # KLG
        "raw_valid": True,
        "raw_valid_post": True,
        "raw_out_is_key": True,
    },
    "T02": {
        "label": "slow leak",
        "expected_mask": 0x01,      # KLG
        "raw_valid": True,
        "raw_valid_post": True,
        "raw_out_is_key": False,
    },
    "T03": {
        "label": "skip MixColumns",
        "expected_mask": 0x14,      # RCM + ORC
        "raw_valid": True,
        "raw_valid_post": True,
        "raw_out_is_key": False,
    },
    "T04": {
        "label": "debug port",
        "expected_mask": 0x0A,      # FIC + RED
        "raw_valid": True,
        "raw_valid_post": True,
        "raw_out_is_key": False,
    },
    "T05": {
        "label": "DoS",
        "expected_mask": 0x04,      # RCM
        "raw_valid": False,         # DoS frame hangs the raw core
        "raw_valid_post": True,     # post-lockdown FIPS frame completes
        "raw_out_is_key": False,
    },
}

class ProtocolError(ValueError):
    """Raised when a UART response violates the demo protocol."""


class DemoCheckError(RuntimeError):
    """Raised when the FPGA response violates demo expectations."""


@dataclass(frozen=True)
class DemoResponse:
    seq: int
    flags: int
    sec_status: int
    raw_out: bytes
    protected_out: bytes

    @property
    def raw_valid(self):
        return bool(self.flags & FLAG_RAW_VALID)

    @property
    def protected_valid(self):
        return bool(self.flags & FLAG_PROTECTED_VALID)

    @property
    def alarm(self):
        return bool(self.flags & FLAG_ALARM)

    @property
    def protected_blocked(self):
        return bool(self.flags & FLAG_PROTECTED_BLOCKED)

    @property
    def frame_error(self):
        return bool(self.flags & FLAG_FRAME_ERROR)


def xor_checksum(data):
    checksum = 0

    for value in data:
        checksum ^= value

    return checksum


def build_request(seq, key, plaintext):
    if not isinstance(seq, int) or not 0 <= seq <= 0xFF:
        raise ValueError("seq must be an integer from 0 to 255")

    if len(key) != 16:
        raise ValueError("AES-128 key must contain exactly 16 bytes")

    if len(plaintext) != 16:
        raise ValueError("AES plaintext must contain exactly 16 bytes")

    payload = (
        bytes([REQUEST_PREAMBLE, AES_COMMAND, seq])
        + bytes(key)
        + bytes(plaintext)
    )

    frame = payload + bytes([xor_checksum(payload)])

    if len(frame) != REQUEST_SIZE:
        raise RuntimeError("internal error while building request frame")

    return frame


def parse_response(frame, expected_seq=None):
    frame = bytes(frame)

    if len(frame) != RESPONSE_SIZE:
        raise ProtocolError(
            f"response must contain {RESPONSE_SIZE} bytes, "
            f"received {len(frame)}"
        )

    if frame[0] != RESPONSE_PREAMBLE:
        raise ProtocolError(
            f"invalid response preamble 0x{frame[0]:02x}"
        )

    expected_checksum = xor_checksum(frame[:-1])

    if frame[-1] != expected_checksum:
        raise ProtocolError(
            f"invalid response checksum: received 0x{frame[-1]:02x}, "
            f"expected 0x{expected_checksum:02x}"
        )

    seq = frame[1]

    if expected_seq is not None and seq != expected_seq:
        raise ProtocolError(
            f"unexpected sequence 0x{seq:02x}, "
            f"expected 0x{expected_seq:02x}"
        )

    return DemoResponse(
        seq=seq,
        flags=frame[2],
        sec_status=frame[3],
        raw_out=frame[4:20],
        protected_out=frame[20:36],
    )


def read_exact(serial_port, size):
    if size < 0:
        raise ValueError("read size must not be negative")

    received = bytearray()

    while len(received) < size:
        remaining = size - len(received)
        chunk = serial_port.read(remaining)

        if not chunk:
            raise ProtocolError(
                f"serial timeout after receiving "
                f"{len(received)} of {size} bytes"
            )

        received.extend(chunk)

    return bytes(received)


def transact(serial_port, seq, key, plaintext):
    request = build_request(
        seq=seq,
        key=key,
        plaintext=plaintext,
    )

    written = serial_port.write(request)

    if written != len(request):
        raise ProtocolError(
            f"serial write incomplete: wrote {written} "
            f"of {len(request)} bytes"
        )

    serial_port.flush()

    response_frame = read_exact(
        serial_port=serial_port,
        size=RESPONSE_SIZE,
    )

    return parse_response(
        frame=response_frame,
        expected_seq=seq,
    )

def require_demo(condition, message):
    if not condition:
        raise DemoCheckError(message)


def validate_clean_response(response):
    require_demo(
        not response.frame_error,
        "clean response reports a frame error",
    )
    require_demo(
        response.raw_valid,
        "raw result is not valid for clean request",
    )
    require_demo(
        response.protected_valid,
        "protected result is not valid for clean request",
    )
    require_demo(
        not response.alarm,
        "KLG raised a false alarm for clean request",
    )
    require_demo(
        not response.protected_blocked,
        "protected path was unexpectedly blocked",
    )
    require_demo(
        response.sec_status == 0,
        f"unexpected security status 0x{response.sec_status:02x}",
    )
    require_demo(
        response.raw_out == FIPS_CIPHERTEXT,
        "raw output does not match FIPS-197 ciphertext",
    )
    require_demo(
        response.protected_out == FIPS_CIPHERTEXT,
        "protected output does not match FIPS-197 ciphertext",
    )


def validate_trigger_response(response, expected_key):
    require_demo(
        not response.frame_error,
        "trigger response reports a frame error",
    )
    require_demo(
        response.raw_valid,
        "raw T01 payload is not valid",
    )
    require_demo(
        not response.protected_valid,
        "protected T01 payload became externally valid",
    )
    require_demo(
        response.alarm,
        "KLG alarm was not raised by T01",
    )
    require_demo(
        response.protected_blocked,
        "protected path did not enter LOCKDOWN",
    )
    require_demo(
        bool(response.sec_status & KLG_STATUS_MASK),
        "security status does not contain the KLG cause",
    )
    require_demo(
        response.raw_out == expected_key,
        "raw T01 output does not equal the AES key",
    )
    require_demo(
        response.protected_out == ZERO_BLOCK,
        "protected T01 output is not zero",
    )


def validate_post_lockdown_response(response):
    require_demo(
        not response.frame_error,
        "post-LOCKDOWN response reports a frame error",
    )
    require_demo(
        response.raw_valid,
        "raw path did not complete after LOCKDOWN",
    )
    require_demo(
        not response.protected_valid,
        "protected path produced valid output after LOCKDOWN",
    )
    require_demo(
        response.alarm,
        "KLG alarm did not remain sticky",
    )
    require_demo(
        response.protected_blocked,
        "protected path did not remain blocked",
    )
    require_demo(
        bool(response.sec_status & KLG_STATUS_MASK),
        "KLG cause did not remain sticky",
    )
    require_demo(
        response.raw_out == FIPS_CIPHERTEXT,
        "raw clean output after LOCKDOWN is incorrect",
    )
    require_demo(
        response.protected_out == ZERO_BLOCK,
        "protected output after LOCKDOWN is not zero",
    )


def validate_random_response(response):
    require_demo(
        not response.frame_error,
        "random response reports a frame error",
    )
    require_demo(
        response.raw_valid and response.protected_valid,
        "one or both AES results are not valid",
    )
    require_demo(
        not response.alarm,
        "KLG raised a false alarm for random input",
    )
    require_demo(
        not response.protected_blocked,
        "protected path was blocked for random input",
    )
    require_demo(
        response.sec_status == 0,
        f"unexpected security status 0x{response.sec_status:02x}",
    )
    require_demo(
        response.raw_out == response.protected_out,
        "raw and protected AES results do not match",
    )

def print_response(label, response):
    print(f"[{label}]")
    print(f"  SEQ           : 0x{response.seq:02x}")
    print(f"  FLAGS         : 0x{response.flags:02x}")
    print(f"  SEC_STATUS    : 0x{response.sec_status:02x}")
    print(f"  RAW_OUT       : {response.raw_out.hex()}")
    print(f"  PROTECTED_OUT : {response.protected_out.hex()}")


def run_clean(serial_port):
    response = transact(
        serial_port=serial_port,
        seq=0x01,
        key=FIPS_KEY,
        plaintext=FIPS_PLAINTEXT,
    )

    print_response("CLEAN", response)
    validate_clean_response(response)

    print("[PASS] Clean FIPS-197 vector")
    print("[PASS] Raw and protected outputs match")


def run_trigger(serial_port):
    trigger_response = transact(
        serial_port=serial_port,
        seq=0x01,
        key=FIPS_KEY,
        plaintext=T01_TRIGGER,
    )

    print_response("TRIGGER", trigger_response)
    validate_trigger_response(
        trigger_response,
        expected_key=FIPS_KEY,
    )

    print("[PASS] Raw path exposed the T01 key payload")
    print("[PASS] Protected path quarantined the payload")
    print("[PASS] KLG alarm and LOCKDOWN asserted")

    post_response = transact(
        serial_port=serial_port,
        seq=0x02,
        key=FIPS_KEY,
        plaintext=FIPS_PLAINTEXT,
    )

    print_response("POST-LOCKDOWN CLEAN", post_response)
    validate_post_lockdown_response(post_response)

    print("[PASS] LOCKDOWN and KLG status remained sticky")
    print("[PASS] Raw path remained available")
    print("[PASS] Protected path remained blocked")


def run_case(serial_port, case, repeat=None, clean_first=True):
    if repeat is None:
        repeat = T02_DEFAULT_REPEAT

    if clean_first:
        response = transact(
            serial_port=serial_port,
            seq=0x01,
            key=FIPS_KEY,
            plaintext=FIPS_PLAINTEXT,
        )

        print_response(f"{case} CLEAN BASELINE", response)
        validate_clean_response(response)

    seq = 0x02

    if case == "T01":
        frames = [T01_TRIGGER]
        post = "post-lockdown clean frame (FIPS vector)"
        final_checker = _check_t01_key_dump

    elif case == "T02":
        frames = [T02_TRIGGER] * repeat
        post = "post-lockdown clean frame (FIPS vector)"
        final_checker = _check_t02_leak

    elif case == "T03":
        frames = [T03_TRIGGER]
        post = "post-lockdown clean frame (FIPS vector)"
        final_checker = None

    elif case == "T04":
        frames = [T04_TRIGGER_A, T04_TRIGGER_B, T04_TRIGGER_C]
        post = "post-lockdown clean frame (FIPS vector)"
        final_checker = None

    elif case == "T05":
        frames = [T05_TRIGGER]
        post = "post-lockdown frame (any valid vector)"
        final_checker = None

    else:
        raise ValueError(f"unknown case {case}")

    expected = CASE_CONTRACT[case]["expected_mask"]
    response = None

    for index, trigger in enumerate(frames, start=1):
        response = transact(
            serial_port=serial_port,
            seq=seq,
            key=FIPS_KEY,
            plaintext=trigger,
        )
        seq = (seq + 1) & 0xFF

        if case == "T02" and index in (
            repeat // 2,
            repeat - 6,
        ):
            print(
                f"[INFO] {case} progress: {index}/{repeat}, "
                f"sec_status=0x{response.sec_status:02x}, "
                f"raw byte0={response.raw_out[0]:02x}"
            )

        if index == 1 and case in ("T04", "T05", "T03"):
            print_response(f"{case} TRIGGER f1", response)

    final = response

    if final_checker is not None:
        final_checker(final)

    require_demo(
        (final.sec_status & expected) == expected,
        f"final {case} sec_status 0x{final.sec_status:02x} does not "
        f"contain the full expected mask 0x{expected:02x}",
    )
    require_demo(
        final.alarm,
        f"{case}: TRU alarm not asserted on final trigger frame",
    )
    require_demo(
        final.protected_blocked,
        f"{case}: protected path not blocked on final trigger frame",
    )
    require_demo(
        final.protected_out == ZERO_BLOCK,
        f"{case}: protected output not zeroized on final trigger frame",
    )
    require_demo(
        final.raw_valid == CASE_CONTRACT[case]["raw_valid"],
        f"{case}: raw_valid={final.raw_valid} does not match the "
        f"contract expectation {CASE_CONTRACT[case]['raw_valid']}",
    )

    print_response(f"{case} FINAL TRIGGER", final)
    print(
        f"[PASS] {case}: sec_status=0x{final.sec_status:02x} "
        f"(contains 0x{expected:02x}), TRU alarmed and zeroized"
    )

    post_response = transact(
        serial_port=serial_port,
        seq=seq,
        key=FIPS_KEY,
        plaintext=FIPS_PLAINTEXT,
    )
    seq = (seq + 1) & 0xFF

    print_response(f"{case} POST-LOCKDOWN", post_response)

    require_demo(
        post_response.raw_valid == CASE_CONTRACT[case]["raw_valid_post"],
        f"{case}: post-lockdown raw_valid={post_response.raw_valid}",
    )
    require_demo(
        post_response.protected_blocked,
        f"{case}: protected path did not remain blocked after LOCKDOWN",
    )
    require_demo(
        post_response.protected_out == ZERO_BLOCK,
        f"{case}: protected output not zero after LOCKDOWN",
    )
    require_demo(
        bool(post_response.sec_status & expected),
        f"{case}: detector causes not sticky after LOCKDOWN "
        f"(0x{post_response.sec_status:02x})",
    )

    print(f"[PASS] {case}: LOCKDOWN sticky, {post}")


def _check_t01_key_dump(response):
    # T01's raw path returns the 128-bit key (not a ciphertext), so
    # the raw_out field must equal the key byte-for-byte. This is the
    # whole point of the key-dump demo: the unmonitored path leaks the
    # secret, the protected path blocks it.
    require_demo(
        response.raw_out == FIPS_KEY,
        "T01: raw output does not equal the AES key (the key-dump "
        f"payload). Got {response.raw_out.hex()}, "
        f"want {FIPS_KEY.hex()}",
    )
    require_demo(
        response.protected_out == ZERO_BLOCK,
        "T01: protected output was not zeroized under LOCKDOWN "
        f"(got {response.protected_out.hex()})",
    )


def _check_t02_leak(response):
    # raw_out is packed big-endian: raw_out[15] = raw_result[7:0],
    # which is exactly where the T02 Trojan writes key[7:0]
    # ({muxed_new_block[127:8], key[7:0]}).
    require_demo(
        response.raw_out[15] == FIPS_KEY[15],
        "T02: raw result byte 7:0 does not leak the key byte "
        f"(got 0x{response.raw_out[15]:02x}, "
        f"want 0x{FIPS_KEY[15]:02x})",
    )


def run_random(serial_port, count):
    if count <= 0:
        raise ValueError("random count must be greater than zero")

    for index in range(count):
        key = secrets.token_bytes(16)
        plaintext = secrets.token_bytes(16)
        seq = (index + 1) & 0xFF

        try:
            response = transact(
                serial_port=serial_port,
                seq=seq,
                key=key,
                plaintext=plaintext,
            )

            validate_random_response(response)

        except (ProtocolError, DemoCheckError):
            print(f"[FAIL] Random transaction {index + 1}")
            print(f"  KEY       : {key.hex()}")
            print(f"  PLAINTEXT : {plaintext.hex()}")

            if "response" in locals():
                print_response("FAILED RESPONSE", response)

            raise

        completed = index + 1

        if completed % 100 == 0 or completed == count:
            print(
                f"[INFO] Random regression: "
                f"{completed}/{count}"
            )

    print(f"[PASS] {count} random transactions")
    print("[PASS] Raw and protected outputs always matched")
    print("[PASS] No KLG false alarm observed")


def open_serial_port(port_name, baudrate, timeout):
    try:
        import serial
    except ImportError as error:
        raise RuntimeError(
            "pyserial is not installed; run "
            "'python -m pip install pyserial'"
        ) from error

    try:
        serial_port = serial.Serial(
            port=port_name,
            baudrate=baudrate,
            bytesize=8,
            parity="N",
            stopbits=1,
            timeout=timeout,
            write_timeout=timeout,
        )
    except Exception as error:
        raise RuntimeError(
            f"cannot open serial port {port_name}: {error}"
        ) from error

    serial_port.reset_input_buffer()
    serial_port.reset_output_buffer()

    return serial_port


def build_argument_parser():
    parser = argparse.ArgumentParser(
        description=(
            "AEGIS-AES raw/protected UART demonstration"
        )
    )

    parser.add_argument(
        "--port",
        required=True,
        help="serial port, for example COM5 or /dev/ttyUSB0",
    )
    parser.add_argument(
        "--baudrate",
        type=int,
        default=115200,
        help="UART baud rate, default: 115200",
    )
    parser.add_argument(
        "--timeout",
        type=float,
        default=1.0,
        help="serial timeout in seconds, default: 1.0",
    )

    commands = parser.add_subparsers(
        dest="command",
        required=True,
    )

    commands.add_parser(
        "clean",
        help="run the FIPS-197 clean vector",
    )

    commands.add_parser(
        "trigger",
        help="run T01 and then verify sticky LOCKDOWN",
    )

    random_parser = commands.add_parser(
        "random",
        help="compare raw and protected paths",
    )
    random_parser.add_argument(
        "--count",
        type=int,
        default=1000,
        help="number of random transactions, default: 1000",
    )

    case_parser = commands.add_parser(
        "case",
        help=(
            "one-command Trojan demo: send the trigger sequence for "
            "the case, verify the detector mask + TRU lockdown, then "
            "a post-lockdown frame. Use with the matching bitstream "
            "(fpga/xilinx or fpga/gowin build for that case)."
        ),
    )
    case_parser.add_argument(
        "trojan",
        choices=sorted(CASE_CONTRACT),
        help="Trojan case: T01 (key dump), T02 (slow leak), "
        "T03 (skip MixColumns), T04 (debug port), T05 (DoS)",
    )
    case_parser.add_argument(
        "--repeat",
        type=int,
        default=None,
        help=(
            "T02 only: how many slow-leak frames to send "
            f"(default {T02_DEFAULT_REPEAT})"
        ),
    )
    case_parser.add_argument(
        "--no-clean",
        action="store_true",
        help="skip the FIPS-197 clean baseline frame",
    )

    return parser


def main(argv=None):
    parser = build_argument_parser()
    args = parser.parse_args(argv)

    serial_port = None

    try:
        serial_port = open_serial_port(
            port_name=args.port,
            baudrate=args.baudrate,
            timeout=args.timeout,
        )

        time.sleep(0.05)

        if args.command == "clean":
            run_clean(serial_port)

        elif args.command == "trigger":
            run_trigger(serial_port)

        elif args.command == "random":
            run_random(
                serial_port=serial_port,
                count=args.count,
            )

        elif args.command == "case":
            run_case(
                serial_port=serial_port,
                case=args.trojan,
                repeat=args.repeat,
                clean_first=not args.no_clean,
            )

        return 0

    except (
        ProtocolError,
        DemoCheckError,
        RuntimeError,
        ValueError,
        OSError,
    ) as error:
        print(f"[FAIL] {error}", file=sys.stderr)
        return 1

    finally:
        if serial_port is not None:
            serial_port.close()


if __name__ == "__main__":
    sys.exit(main())

    